def get_care_for_plant(plant_slug, plant_name, category_slug):
    """Returns matching care guide dictionary for any plant slug/name"""
    slug_lower = plant_slug.lower()
    name_lower = plant_name.lower()

    # Exact or keyword matching
    for key, data in PLANT_CARE_GUIDES.items():
        if key in slug_lower or key.replace('-', ' ') in name_lower:
            return data

    # Keyword fallbacks
    if "pothos" in slug_lower or "money" in name_lower:
        return PLANT_CARE_GUIDES["golden-pothos"]
    elif "monstera" in slug_lower:
        return PLANT_CARE_GUIDES["monstera-deliciosa"]
    elif "zz" in slug_lower:
        return PLANT_CARE_GUIDES["zz-plant"]
    elif "lily" in slug_lower:
        return PLANT_CARE_GUIDES["peace-lily"]
    elif "palm" in slug_lower:
        return PLANT_CARE_GUIDES["areca-palm"]
    elif "rubber" in slug_lower or "ficus" in slug_lower:
        return PLANT_CARE_GUIDES["rubber-plant"]
    elif "jade" in slug_lower or "crassula" in slug_lower:
        return PLANT_CARE_GUIDES["crassula-jade"]
    elif "bougainvillea" in slug_lower:
        return PLANT_CARE_GUIDES["bougainvillea"]
    elif "hibiscus" in slug_lower:
        return PLANT_CARE_GUIDES["hibiscus"]
    elif "adenium" in slug_lower or "desert" in slug_lower:
        return PLANT_CARE_GUIDES["adenium"]
    elif "bamboo" in slug_lower:
        return PLANT_CARE_GUIDES["golden-bamboo"]
    elif "jasmine" in slug_lower or "mogra" in slug_lower:
        return PLANT_CARE_GUIDES["mogra"]
    elif "rose" in slug_lower:
        return PLANT_CARE_GUIDES["dutch-red-rose"]
    elif "marigold" in slug_lower:
        return PLANT_CARE_GUIDES["marigold"]
    elif "lemon" in slug_lower or "lime" in slug_lower:
        return PLANT_CARE_GUIDES["kagzi-lemon"]
    elif "mango" in slug_lower:
        return PLANT_CARE_GUIDES["amrapali-mango"]
    elif "pomegranate" in slug_lower:
        return PLANT_CARE_GUIDES["bhagwa-pomegranate"]
    elif "tulsi" in slug_lower:
        return PLANT_CARE_GUIDES["krishna-tulsi"]
    elif "aloe" in slug_lower:
        return PLANT_CARE_GUIDES["aloe-vera"]
    elif "ajwain" in slug_lower or "borage" in slug_lower:
        return PLANT_CARE_GUIDES["indian-borage"]
    elif "haworthia" in slug_lower or "succulent" in slug_lower:
        return PLANT_CARE_GUIDES["haworthia-zebra"]

    # Category generalized fallback
    if "indoor" in category_slug:
        return PLANT_CARE_GUIDES["golden-pothos"]
    elif "outdoor" in category_slug:
        return PLANT_CARE_GUIDES["bougainvillea"]
    elif "flower" in category_slug:
        return PLANT_CARE_GUIDES["hibiscus"]
    elif "fruit" in category_slug:
        return PLANT_CARE_GUIDES["kagzi-lemon"]
    else:
        return PLANT_CARE_GUIDES["krishna-tulsi"]
